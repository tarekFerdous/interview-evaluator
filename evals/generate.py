"""Writes synthetic labelled cases with a different model from the grader.

    uv run python -m evals.generate                       # every role x quality, skipping existing files
    uv run python -m evals.generate --role backend --quality weak --force

Cases are saved with reviewed: false. The draft labels are the generator's intent; review and
correct them, then set reviewed: true so the runner counts them.
"""

import argparse
import sys
from pathlib import Path
from typing import Literal

import anthropic
from dotenv import load_dotenv
from pydantic import BaseModel, Field

from interview_evaluator.models import QA, Recommendation

from .dataset import CASES_DIR, Case, Expected

GENERATOR_MODEL = "claude-sonnet-5-5"  # not the grading model, so the grader isn't scoring its own style

Quality = Literal["strong", "mixed", "weak"]

ROLES = {
    "applied-ai": "Applied AI Engineer building LLM features, RAG and evals in Python",
    "backend": "Backend Engineer building Python/FastAPI services on Postgres",
    "data-engineer": "Data Engineer owning batch and streaming pipelines and data quality",
    "frontend": "Frontend Engineer building accessible React/TypeScript product UI",
    "eng-manager": "Engineering Manager leading a team of 6-8 engineers",
}

QUALITY_BRIEF = {
    "strong": "a strong candidate: specific, verifiable detail (numbers, trade-offs, ownership) on most "
    "competencies; scores mostly 4-5",
    "mixed": "a mixed candidate: strong on some competencies and vague or missing on others; scores "
    "spread across 1-5",
    "weak": "a weak candidate: vague, generic or incorrect answers; scores mostly 1-2",
}

SYSTEM_PROMPT = """You write realistic synthetic interview transcripts for an evaluation dataset \
that measures how well an AI grader scores candidates.

Scoring scale for each rubric competency (the grader uses the same one):
1 = no evidence, 2 = weak or vague, 3 = adequate, 4 = strong, 5 = strong with specific, \
verifiable detail (numbers, trade-offs, ownership).

Write the transcript first, then score it honestly against the scale as a careful human \
interviewer would. The scores must be justified by what the candidate actually said. Use the \
rubric competency names exactly as you list them. Never include names or personal details."""


class LabelledScore(BaseModel):
    competency: str
    score: int = Field(description="1-5")


class GeneratedCase(BaseModel):
    job_description: str
    rubric: list[str] = Field(description="3-5 competencies")
    transcript: list[QA] = Field(description="4-6 question/answer pairs")
    expected_scores: list[LabelledScore] = Field(description="One per rubric competency")
    expected_recommendation: Recommendation
    notes: str = Field(description="One or two sentences on why the scores are what they are")


def generate_case(
    role: str, quality: Quality, client: anthropic.Anthropic | None = None
) -> Case:
    client = client or anthropic.Anthropic()
    response = client.beta.messages.parse(
        model=GENERATOR_MODEL,
        max_tokens=16000,
        system=SYSTEM_PROMPT,
        messages=[
            {
                "role": "user",
                "content": f"Role: {ROLES[role]}\nCandidate: {QUALITY_BRIEF[quality]}\n\n"
                "Write the job description, rubric, transcript and expected labels.",
            }
        ],
        output_format=GeneratedCase,
        output_config={"effort": "medium"},
        betas=["server-side-fallback-2026-07-01"],
        fallbacks="default",
    )
    g = response.parsed_output
    if g is None:
        raise RuntimeError(f"No structured output (stop_reason={response.stop_reason})")
    return Case(
        id=f"{role}-{quality}",
        reviewed=False,
        notes=f"Generated by {GENERATOR_MODEL}; draft labels, needs review. {g.notes}",
        request={"job_description": g.job_description, "rubric": g.rubric, "transcript": g.transcript},
        expected=Expected(
            scores={s.competency: s.score for s in g.expected_scores},
            recommendation=g.expected_recommendation,
        ),
    )


def main(argv: list[str] | None = None, client: anthropic.Anthropic | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m evals.generate", description=__doc__.splitlines()[0])
    p.add_argument("--role", choices=list(ROLES), action="append")
    p.add_argument("--quality", choices=list(QUALITY_BRIEF), action="append")
    p.add_argument("--out-dir", type=Path, default=CASES_DIR)
    p.add_argument("--force", action="store_true", help="Overwrite existing case files")
    args = p.parse_args(argv)

    client = client or anthropic.Anthropic()
    args.out_dir.mkdir(parents=True, exist_ok=True)
    failures = 0
    for role in args.role or ROLES:
        for quality in args.quality or QUALITY_BRIEF:
            path = args.out_dir / f"{role}-{quality}.json"
            if path.exists() and not args.force:
                print(f"skip {path.name} (exists)", file=sys.stderr)
                continue
            try:
                case = generate_case(role, quality, client)
            except (anthropic.APIError, RuntimeError, ValueError) as e:
                failures += 1
                print(f"FAILED {path.name}: {type(e).__name__}: {e}", file=sys.stderr)
                continue
            path.write_text(case.model_dump_json(indent=2) + "\n", encoding="utf-8")
            print(f"wrote {path.name}", file=sys.stderr)
    return 1 if failures else 0


if __name__ == "__main__":
    load_dotenv()
    sys.exit(main())
